$ValueCount = 0
foreach ($v in $Values) {
    $ValueCount++
    $Name = $v.Name
    
    # Find conflicting values (at least 3)
    $Conflicts = @()
    $AvailableConflicts = $Values | Where-Object { $_.Name -ne $Name } | Get-Random -Count 4
    foreach ($c in $AvailableConflicts) {
        $reason = @(
            "противоположные приоритеты",
            "взаимоисключающие подходы",
            "конкуренция за ресурсы",
            "различные ценности",
            "прямое противостояние"
        ) | Get-Random -Count 1
        $Conflicts += "- [[$($c.Name)]] — конфликт из-за $reason"
    }
    
    # Find balancing principles (2-3)
    $BalancePrinciples = @("Принцип наименьшего насилия", "Принцип справедливости", "Принцип равенства", "Принцип свободы", "Принцип ответственности") | Get-Random -Count 2
    
