def make_id(cluster_name: str, node_type: str) -> str:
    return f"{cluster_name}_{node_type}"

def make_filename(title: str) -> str:
    # Transliterate for filename
    translit = {
        'а':'a','б':'b','в':'v','г':'g','д':'d','е':'e','ё':'yo','ж':'zh','з':'z',
        'и':'i','й':'y','к':'k','л':'l','м':'m','н':'n','о':'o','п':'p','р':'r',
        'с':'s','т':'t','у':'u','ф':'f','х':'kh','ц':'ts','ч':'ch','ш':'sh','щ':'sch',
        'ъ':'','ы':'y','ь':'','э':'e','ю':'yu','я':'ya',
        'А':'A','Б':'B','В':'V','Г':'G','Д':'D','Е':'E','Ё':'Yo','Ж':'Zh','З':'Z',
        'И':'I','Й':'Y','К':'K','Л':'L','М':'M','Н':'N','О':'O','П':'P','Р':'R',
        'С':'S','Т':'T','У':'U','Ф':'F','Х':'Kh','Ц':'Ts','Ч':'Ch','Ш':'Sh','Щ':'Sch',
        'Ъ':'','Ы':'Y','Ь':'','Э':'E','Ю':'Yu','Я':'Ya',
    }
    result = ""
    for ch in title:
        result += translit.get(ch, ch)
    # Clean up filename
    result = result.replace(" ", "_").replace("/", "-").replace("\\", "-")
    result = "".join(c for c in result if c.isalnum() or c in "_-")
    return result[:80]

def add_link(source_id: str, target_id: str, rel: str):
    """Add a link from source to target with relationship."""
    if source_id not in nodes:
        return
    if target_id not in nodes:
        return
    nodes[source_id]["links"].append((target_id, rel))
    link_counter[source_id] = link_counter.get(source_id, 0) + 1
    link_counter[target_id] = link_counter.get(target_id, 0) + 1

