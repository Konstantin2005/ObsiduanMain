def create_feedback_loop_note(name, description, polarity, cycle_nodes, reinforces, weakens, breaks):
    cycle_str = " → ".join(cycle_nodes)
    reinforce_list = "\n".join(f"- [[{r}]]" for r in reinforces)
    weakens_list = "\n".join(f"- [[{w}]]" for w in weakens)
    breaks_list = "\n".join(f"- [[{b}]]" for b in breaks)
    
    content = f"""---
type: FeedbackLoop
polarity: {polarity}
tags: [feedback, causal]
---

# {name}

## Описание
{description}

## Замыкает цикл
{cycle_str}

## Полярность
{polarity}

## Усиливает
{reinforce_list}

## Ослабляет
{weakens_list}

## Разрывает
{breaks_list}
"""
    
    filepath = os.path.join(BASE_DIR, "FeedbackLoops", f"{name}.md")
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(content)
    loop_names.append(name)


