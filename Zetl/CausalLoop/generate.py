def create_event_note(name, description, impact, scale, causes, effects, feedback_loops, related_events):
    causes_list = "\n".join(f"- [[{c}]]" for c in causes)
    effects_list = "\n".join(f"- [[{e}]]" for e in effects)
    feedback_list = "\n".join(f"- [[{f}]]" for f in feedback_loops)
    related_list = "\n".join(f"- [[{r}]]" for r in related_events)
    
    content = f"""---
type: Event
impact: {impact}
scale: {scale}
tags: [event, causal]
---

# {name}

## Описание
{description}

## Причины
{causes_list}

## Последствия
{effects_list}

## Обратные связи
{feedback_list}

## Связанные события
{related_list}
"""
    
    filepath = os.path.join(BASE_DIR, "Events", f"{name}.md")
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(content)
    event_names.append(name)


