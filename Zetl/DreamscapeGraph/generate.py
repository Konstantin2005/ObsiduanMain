def sanitize_filename(name: str) -> str:
    return name.replace("/", "-").replace("\\", "-").replace(":", " -")


def make_links(links: list[str], all_names: set[str]) -> str:
    lines = []
    for link in links:
        if link in all_names:
            lines.append(f"- [[{link}]]")
        else:
            lines.append(f"- {link}")
    return "\n".join(lines)


def generate_note(section_dir: Path, note_type: str, title: str, description: str,
                  links: list[str], all_names: set[str]) -> None:
    filename = sanitize_filename(title) + ".md"
    filepath = section_dir / filename

    links_str = make_links(links, all_names)

    content = f"""---
type: {note_type}
tags: [dreamscape]
---
# {title}

{description}

## Связи

{links_str}
"""

    filepath.write_text(content, encoding="utf-8")


def generate_moc_graph(section_dirs: dict[str, Path], all_notes: dict[str, list[str]]) -> Path:
    lines = [
        "---",
        "tags: [dreamscape, moc]",
        "---",
        "# DreamscapeGraph",
        "",
        "Карта мира сновидений. Все пути ведут в глубину.",
        "",
    ]

    for section_name, folder in section_dirs.items():
        note_type, notes = SECTIONS[section_name]
        lines.append(f"## {section_name}")
        lines.append("")
        for title, _, _ in notes:
            lines.append(f"- [[{title}]]")
        lines.append("")

    filepath = section_dirs["Dreams"].parent / "MOC DreamscapeGraph.md"
    filepath.write_text("\n".join(lines), encoding="utf-8")
    return filepath


