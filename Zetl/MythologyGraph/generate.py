def ensure_dirs():
    for d in ["Gods", "Titans", "Heroes", "Monsters", "Artifacts", "Realms", "Prophecies"]:
        (BASE_DIR / d).mkdir(parents=True, exist_ok=True)

def note_path(category, name):
    return BASE_DIR / category / f"{name}.md"

def write_note(category, name, note_type, desc, tags_extra=None, links=None):
    tags = ["mythology"]
    if tags_extra:
        tags.extend(tags_extra)
    tags_str = ", ".join(tags)
    links = links or []
    links_block = ""
    if links:
        links_block = "\n## Связи\n" + "\n".join(f"- [[{l}]]" for l in links)
    content = f"""---
type: {note_type}
tags: [{tags_str}]
---
# {name}
{desc}
{links_block}
"""
    p = note_path(category, name)
    p.write_text(content, encoding="utf-8")

