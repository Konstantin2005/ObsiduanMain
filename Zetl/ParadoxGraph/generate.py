# ── вспомогательные функции ──────────────────────────────────────────────
def write_file(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def frontmatter(note_type: str, tags: list[str]) -> str:
    tag_str = ", ".join(tags)
    return f"---\ntype: {note_type}\ntags: [{tag_str}]\n---\n"


def render_note(
    name: str,
    desc: str,
    essence: str,
    contras: list[str],
    links: list[str],
    note_type: str,
    tags: list[str],
) -> str:
    desc = desc or name
    lines = [frontmatter(note_type, tags), f"# {name}\n", f"{desc}\n"]
    lines.append("## Суть\n")
    lines.append(f"{essence}\n")
    if contras:
        lines.append("## Контрапарадоксы\n")
        for c in contras:
            lines.append(f"- [[{c}]]\n")
    if links:
        lines.append("## Связи\n")
        for l in links:
            lines.append(f"- [[{l}]]\n")
    return "".join(lines)


def generate_notes(
    directory: Path,
    items: list[dict],
    note_type: str,
    tags: list[str],
) -> list[str]:
    directory.mkdir(parents=True, exist_ok=True)
    names = []
    for item in items:
        filename = item["name"].replace("/", "-") + ".md"
        filepath = directory / filename
        content = render_note(
            item["name"],
            item.get("desc", ""),
            item.get("essence", ""),
            item.get("contras", []),
            item.get("links", []),
            note_type,
            tags,
        )
        write_file(filepath, content)
        names.append(item["name"])
    return names


def generate_moc_paradox_graph(all_names: dict[str, list[str]]) -> str:
    lines = [
        frontmatter("moc", ["paradox", "moc"]),
        "# MOC: Парадоксы\n",
    ]
    for section, names in all_names.items():
        lines.append(f"## {section}\n")
        for n in names:
            lines.append(f"- [[{n}]]\n")
    return "".join(lines)


def generate_moc_global(all_names: dict[str, list[str]]) -> str:
    total = sum(len(v) for v in all_names.values())
    lines = [
        frontmatter("moc", ["global", "paradox"]),
        "# MOC: Глобальная карта\n",
        f"Всего заметок: **{total}**\n",
    ]
    for section, names in all_names.items():
        lines.append(f"## {section} ({len(names)})\n")
        for n in names:
            lines.append(f"- [[{n}]]\n")
    return "".join(lines)


def generate_navigation(all_names: dict[str, list[str]]) -> str:
    lines = [
        frontmatter("navigation", ["paradox", "navigation"]),
        "# Навигация по парадоксам\n",
        "## Быстрый старт\n",
        "- [[MOC ParadoxGraph]] — основной индекс\n",
        "- [[MOC Global]] — глобальная карта\n",
        "## По категориям\n",
    ]
    section_map = {
        "Парадоксы": "Paradoxes",
        "Противоречия": "Contradictions",
        "Антиномии": "Antinomies",
        "Бесконечный регресс": "InfiniteRegress",
        "Невозможные объекты": "ImpossibleObjects",
    }
    for ru, en in section_map.items():
        count = len(all_names.get(en, []))
        lines.append(f"### {ru} ({count})\n")
        lines.append(f"- [[MOC ParadoxGraph#{ru}|→ полный список]]\n")
    lines.append("\n## Случайный парадокс\n")
    import random
    random.seed(42)
    all_items = []
    for names in all_names.values():
        all_items.extend(names)
    sample = random.sample(all_items, min(5, len(all_items)))
    for s in sample:
        lines.append(f"- [[{s}]]\n")
    return "".join(lines)


