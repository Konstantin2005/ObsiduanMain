def get_concepts_for_level(level: int) -> list[tuple[str, str]]:
    if level == 0:
        return CONCEPTS
    if level == 1:
        return LEVEL2_CONCEPTS
    if level == 2:
        return LEVEL3_CONCEPTS
    if level == 3:
        return LEVEL4_CONCEPTS
    if level == 4:
        return LEVEL4_DEEP_CONCEPTS
    return []


def create_dirs():
    for name in LEVELS:
        (BASE_DIR / name).mkdir(parents=True, exist_ok=True)


def make_frontmatter(level: int) -> str:
    return (
        "---\n"
        "type: fractal\n"
        f"level: {level}\n"
        "tags: [fractal]\n"
        "---"
    )


def random_children_count(level: int) -> int:
    lo, hi = LEVEL_RANGES[level]
    return random.randint(lo, hi)


def generate_notes():
    notes: dict[int, list[dict]] = {}
    all_concepts: dict[str, tuple[str, str]] = {}

    for level in range(5):
        concepts = get_concepts_for_level(level)
        count = random_children_count(level) if level > 0 else random.randint(3, 5)
        selected = random.sample(concepts, min(count, len(concepts)))
        notes[level] = []
        for title, desc in selected:
            all_concepts[title] = (title, desc)
            notes[level].append({
                "title": title,
                "description": desc,
                "level": level,
                "children": [],
                "parent": None,
            })

    for level in range(5):
        if level == 0:
            continue
        parent_level = level - 1
        parents = notes[parent_level]
        available_concepts = [c for c in get_concepts_for_level(level) if c[0] not in all_concepts]
        concept_idx = 0
        for parent in parents:
            child_count = random_children_count(parent_level)
            for _ in range(child_count):
                if concept_idx < len(available_concepts):
                    title, desc = available_concepts[concept_idx]
                    concept_idx += 1
                else:
                    title = f"Концепция_{level}_{len(notes[level])+1}"
                    desc = f"Абстрактная концепция уровня {level}. Связана с родительской идеей через логическое развитие."
                    while title in all_concepts:
                        title += "_"
                all_concepts[title] = (title, desc)
                child = {
                    "title": title,
                    "description": desc,
                    "level": level,
                    "children": [],
                    "parent": parent["title"],
                }
                notes[level].append(child)
                parent["children"].append(title)

    return notes


def write_note(level: int, note: dict):
    lines = [make_frontmatter(level), "", f"# {note['title']}", ""]
    lines.append(note["description"])
    lines.append("")
    lines.append("## Родитель")
    if note["parent"]:
        lines.append(f"- [[{note['parent']}]]")
    else:
        lines.append("- (корневая концепция)")
    lines.append("")
    lines.append("## Дети")
    if note["children"]:
        for child in note["children"]:
            lines.append(f"- [[{child}]]")
    else:
        lines.append("- (нет дочерних концепций)")
    lines.append("")

    filename = note["title"].replace("/", " ").replace("\\", " ")
    path = BASE_DIR / LEVELS[level] / f"{filename}.md"
    path.write_text("\n".join(lines), encoding="utf-8")


def write_moc_fractal(notes: dict):
    lines = [
        "---",
        "type: moc",
        "tags: [moc, fractal]",
        "---",
        "",
        "# MOC FractalGraph",
        "",
        "Карта содержания фрактального графа концепций.",
        "",
    ]
    for level in range(5):
        lines.append(f"## Level {level}")
        lines.append("")
        for note in notes[level]:
            lines.append(f"- [[{note['title']}]]")
        lines.append("")
    path = BASE_DIR / "MOC FractalGraph.md"
    path.write_text("\n".join(lines), encoding="utf-8")


def write_moc_global(notes: dict):
    total = sum(len(v) for v in notes.values())
    lines = [
        "---",
        "type: moc",
        "tags: [moc, global]",
        "---",
        "",
        "# MOC Global",
        "",
        f"Всего заметок: **{total}**",
        "",
        "## Уровни",
        "",
    ]
    for level in range(5):
        count = len(notes[level])
        lines.append(f"- **Level {level}**: {count} заметок")
    lines.append("")
    lines.append("## Корневые концепции")
    lines.append("")
    for note in notes[0]:
        children_count = len(note["children"])
        lines.append(f"- [[{note['title']}]] — {children_count} дочерних")
    lines.append("")
    path = BASE_DIR / "MOC Global.md"
    path.write_text("\n".join(lines), encoding="utf-8")


def write_navigation(notes: dict):
    lines = [
        "---",
        "type: navigation",
        "tags: [navigation, fractal]",
        "---",
        "",
        "# Навигация",
        "",
        "## Быстрая навигация",
        "",
        "- [[MOC FractalGraph|Карта фрактала]]",
        "- [[MOC Global|Глобальная карта]]",
        "",
        "## Уровни",
        "",
    ]
    for level in range(5):
        lines.append(f"### Level {level}")
        lines.append("")
        if notes[level]:
            for i in range(0, len(notes[level]), 3):
                chunk = notes[level][i:i+3]
                items = " | ".join(f"[[{n['title']}]]" for n in chunk)
                lines.append(f"- {items}")
        lines.append("")
    path = BASE_DIR / "Navigation.md"
    path.write_text("\n".join(lines), encoding="utf-8")


def main():
    create_dirs()
    notes = generate_notes()
    total = sum(len(v) for v in notes.values())
    print(f"Создано {total} заметок:")
    for level in range(5):
        print(f"  Level {level}: {len(notes[level])}")
    for level in range(5):
        for note in notes[level]:
            write_note(level, note)
    write_moc_fractal(notes)
    write_moc_global(notes)
    write_navigation(notes)
    print("Готово.")


if __name__ == "__main__":
    main()
