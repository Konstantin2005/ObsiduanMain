def ensure_dirs():
    for d in DIRS:
        (BASE / d).mkdir(parents=True, exist_ok=True)

def note(stock_name, desc, mechanisms, category, extra_links=None):
    links = mechanisms + (extra_links or [])
    link_str = "\n".join(f"- [[{l}]]" for l in links)
    return f"""---
type: {category}
tags: [systems]
---
# {stock_name}

{desc}

## Механизмы

{', '.join(mechanisms)} — эти процессы определяют поведение системы.

## Паттерны

- Накопление происходит экспоненциально до достижения предела
- Истощение ускоряется при увеличении нагрузки
- Начальные условия определяют долгосрочное поведение

## Связи

{link_str}
"""

