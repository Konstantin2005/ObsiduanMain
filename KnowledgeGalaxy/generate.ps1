$rand = [System.Random]::new(12345) # Fixed seed for reproducibility

function Get-RandomLinks {
    param(
        [string[]]$fromList,
        [string[]]$toList,
        [int]$minLinks = 5,
        [int]$maxLinks = 15
    )
    
    $links = @()
    $targetCount = $rand.Next($minLinks, $maxLinks + 1)
    
    # Intra-cluster links (60%)
    $intraCount = [math]::Floor($targetCount * 0.6)
    $intraLinks = $fromList | Where-Object { $_ -ne $currentNote } | Get-Random -Count ([math]::Min($intraCount, $fromList.Count - 1))
    $links += $intraLinks
    
    # Inter-cluster links (40%)
    $interCount = $targetCount - $links.Count
    if ($interCount -gt 0) {
        $interLinks = $toList | Get-Random -Count ([math]::Min($interCount, $toList.Count))
        $links += $interLinks
    }
    
    return $links | Select-Object -Unique | Select-Object -First $maxLinks
}

function New-Note {
    param(
        [string]$Title,
        [string]$Cluster,
        [string]$Topic,
        [string[]]$AllLinks,
        [string[]]$BridgeLinks
    )
    
    $allLinksForNote = @()
    $allLinksForNote += $AllLinks | Select-Object -First 8
    $allLinksForNote += $BridgeLinks | Select-Object -First 7
    $allLinksForNote = $allLinksForNote | Select-Object -Unique | Select-Object -First 15
    
    if ($allLinksForNote.Count -lt 5) {
        $additional = $AllLinks | Where-Object { $_ -notin $allLinksForNote } | Get-Random -Count (5 - $allLinksForNote.Count)
        $allLinksForNote += $additional
    }
    
    $linksMarkdown = ($allLinksForNote | ForEach-Object { "- [[$_]]" }) -join "`n"
    
    $frontmatter = @"
---
type: $Cluster
topic: $Topic
cluster: $Cluster
tags: [knowledge, $Cluster.ToLower()]
---

# $Title

## Связанные концепции
$linksMarkdown
"@
    
    return $frontmatter
}

