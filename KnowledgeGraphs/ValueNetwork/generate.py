def make_id(value_name, node_type, index=None):
    safe = value_name.replace(" ", "_")
    if index is not None:
        return f"{safe}_{node_type}_{index}"
    return f"{safe}_{node_type}"

def add_link(source, target, rel):
    if source not in nodes or target not in nodes:
        return
    nodes[source]["links"].append((target, rel))
    link_count[source] = link_count.get(source, 0) + 1
    link_count[target] = link_count.get(target, 0) + 1

